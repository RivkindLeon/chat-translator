export function buildSystemPrompt(route) {
  const glossaryLines = Object.entries(route.glossary ?? {})
    .map(([from, to]) => `  ${from} → ${to}`)
    .join("\n");

  return [
    `Ты переводишь поток сообщений израильской WhatsApp-группы на ${route.targetLanguage}.`,
    "",
    "ПРАВИЛА",
    '- Сохраняй строку заголовка "Имя · время" ровно как она дана, ничего в ней не меняй.',
    "- Держи разговорный регистр: сленг переводи сленгом, а не канцеляритом.",
    "- Аббревиатуры и сокращения раскрывай, если без этого смысл теряется.",
    "- Ничего не додумывай и не дополняй. Обрывок остаётся обрывком.",
    '- Реплай помечай отдельной строкой: "↪ в ответ на: <краткая суть>".',
    '- Если сообщение адресовано лично владельцу или требует от него действия, начни строку с "⚑".',
    "- Ответь только переводом. Никаких предисловий, пояснений и комментариев от себя.",
    "- Сохраняй структуру исходного текста в точности: переносы строк, отступы, группировку по дням и разделам. Ничего не склеивай и не переупорядочивай.",
    glossaryLines ? `\nГЛОССАРИЙ (имена и термины пиши именно так)\n${glossaryLines}` : "",
  ]
    .filter(Boolean)
    .join("\n");
}

export function renderMessagesForPrompt(items) {
  return items
    .map((m) => {
      const head = `${m.sender} · ${m.clock}${m.prefix ? ` ${m.prefix}` : ""}`;
      const quote = m.replyToBody ? `\n[ответ на: ${m.replyToBody}]` : "";
      return `${head}${quote}\n${m.text}`;
    })
    .join("\n\n");
}


